#!/usr/bin/env python3
"""Builds each child's app folder (ahara/, aria/) from tools/apps.json.

Writes <app>/index.html, config.js, manifest.webmanifest and sw.js. The code
and data live in shared/ and are the same for every app. Run this after
changing anything in shared/ so installed apps refresh their offline copy:

    python3 tools/build_apps.py
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPS = json.loads((ROOT / "tools" / "apps.json").read_text(encoding="utf-8"))
SHARED = ["android-tts.js", "app.js", "world.js", "chess.js", "style.css", "data/words.js", "data/world.js"]
ICONS = ["icons/icon-192.png", "icons/icon-512.png", "icons/icon-maskable-512.png", "icons/apple-touch-icon.png"]

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
<title>{title}</title>
<meta name="theme-color" content="{theme}" />
<meta name="apple-mobile-web-app-capable" content="yes" />
<meta name="mobile-web-app-capable" content="yes" />
<meta name="apple-mobile-web-app-title" content="{short}" />
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="192x192" href="icons/icon-192.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Andika:wght@400;700&family={font}&family=Sniglet:wght@400;800&display=swap">
<link rel="stylesheet" href="../shared/style.css">
<style>:root {{ --sky: {background}; }}</style>
</head>
<!-- Generated by tools/build_apps.py from tools/apps.json. Edit those, not this file. -->
<body>
<div class="backdrop" id="backdrop" aria-hidden="true"></div>

<div class="wrap">
  <div class="update-bar" id="updateBar" hidden role="status"></div>
  <header>
    <div>
      <p class="hello" id="hello"></p>
      <h1 class="name" id="name"></h1>
      <p class="sub" id="sub"></p>
    </div>
    <div class="controls">
      <div class="control-row">
        <div class="stars" aria-live="polite">⭐ <span id="starCount">0</span></div>
        <button type="button" class="sound-btn" id="soundBtn">🔊 <span id="soundLabel">Sound</span></button>
      </div>
      <div class="lang" role="group" aria-label="Language" id="langs"></div>
    </div>
  </header>

  <nav role="tablist" id="tabs"></nav>

  <main class="panel" id="panel"></main>

  <footer id="footer"></footer>
</div>

<dialog class="sheet" id="soundSheet"></dialog>
<div class="toast" id="toast" hidden></div>
<canvas class="confetti" id="confetti"></canvas>

<script src="config.js"></script>
<script src="../shared/android-tts.js"></script>
<script src="../shared/data/words.js"></script>
{books}
<script src="../shared/data/world.js"></script>
<script src="../shared/world.js"></script>
<script src="../shared/chess.js"></script>
<script src="../shared/app.js"></script>
</body>
</html>
"""

SW = """// Generated by tools/build_apps.py. Offline support: keeps a copy of the app on the device.
// VERSION changes whenever any app file changes, so installed copies refresh.
const VERSION = "{id}-{version}";
const FILES = {files};

self.addEventListener("install", event => {{
  event.waitUntil(caches.open(VERSION).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", event => {{
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith("{id}-") && !k.startsWith(VERSION)).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

self.addEventListener("fetch", event => {{
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // Fonts: use the saved copy, refresh it in the background.
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {{
    event.respondWith(caches.open(VERSION + "-fonts").then(async cache => {{
      const hit = await cache.match(req);
      const net = fetch(req).then(res => {{ cache.put(req, res.clone()); return res; }}).catch(() => hit);
      return hit || net;
    }}));
    return;
  }}
  if (url.origin !== location.origin) return;
  // App files: try the network first so updates arrive, fall back to the saved copy offline.
  event.respondWith(
    fetch(req).then(res => {{
      if (res.ok) {{ const copy = res.clone(); caches.open(VERSION).then(cache => cache.put(req, copy)); }}
      return res;
    }}).catch(() => caches.match(req, {{ ignoreSearch: true }}).then(hit => hit || caches.match("index.html")))
  );
}});
"""


def main():
    for app_id, cfg in APPS.items():
        out = ROOT / app_id
        out.mkdir(exist_ok=True)
        books = [f"data/books-{l}.js" for l in cfg["langs"]]
        config = {"id": app_id, **{k: cfg[k] for k in ("child", "title", "langs", "names", "storePrefix", "downloadPage")}}
        (out / "config.js").write_text(
            "// Generated by tools/build_apps.py from tools/apps.json.\n"
            f"window.APP_CONFIG = {json.dumps(config, ensure_ascii=False, indent=2)};\n", encoding="utf-8")
        page = PAGE.format(books="\n".join(f'<script src="../shared/{b}"></script>' for b in books), **cfg)
        (out / "index.html").write_text(page, encoding="utf-8")
        manifest = {
            "name": cfg["title"], "short_name": cfg["short"], "description": cfg["description"],
            "start_url": "./", "scope": "./", "display": "standalone", "orientation": "any",
            "background_color": cfg["background"], "theme_color": cfg["theme"],
            "icons": [
                {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
                {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
                {"src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}
            ]
        }
        (out / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        files = ["./", "index.html", "config.js", "manifest.webmanifest"] + ICONS + [f"../shared/{f}" for f in SHARED + books]
        digest = hashlib.sha256()
        for f in files[1:]:
            path = (out / f).resolve()
            if path.exists():
                digest.update(path.read_bytes())
        (out / "sw.js").write_text(SW.format(id=app_id, version=digest.hexdigest()[:10], files=json.dumps(files, indent=2)), encoding="utf-8")
        print(f"{app_id}: built ({len(files)} files cached offline)")


if __name__ == "__main__":
    main()
